"""Deterministic fake LLM for tests and offline demos.

Given a JSON schema it synthesises a conforming document; callers can override responses per
`route` (a substring matched against the system prompt or the first user message).
"""

from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

from .base import LLMMessage, LLMResponse


def fill_schema(
    schema: dict[str, Any],
    *,
    defs: dict[str, Any] | None = None,
    key: str = "value",
    depth: int = 0,
) -> Any:
    """Produce a plausible instance of a JSON schema (pydantic-style, with $defs/$ref/anyOf)."""
    defs = defs if defs is not None else schema.get("$defs", {})
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        return fill_schema(defs[name], defs=defs, key=key, depth=depth + 1)
    if "const" in schema:
        return schema["const"]
    if "enum" in schema:
        return schema["enum"][0]
    if "default" in schema and depth > 0:
        return schema["default"]
    if "anyOf" in schema or "oneOf" in schema:
        options = schema.get("anyOf") or schema.get("oneOf")
        non_null = [o for o in options if o.get("type") != "null"]
        return fill_schema((non_null or options)[0], defs=defs, key=key, depth=depth + 1)
    if "allOf" in schema:
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            v = fill_schema(part, defs=defs, key=key, depth=depth + 1)
            if isinstance(v, dict):
                merged.update(v)
        return merged
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), t[0])
    if t == "object" or "properties" in schema:
        out: dict[str, Any] = {}
        for k, sub in (schema.get("properties") or {}).items():
            out[k] = fill_schema(sub, defs=defs, key=k, depth=depth + 1)
        if not out and schema.get("additionalProperties"):
            ap = schema["additionalProperties"]
            out = {
                "note": fill_schema(ap, defs=defs, key="note", depth=depth + 1)
                if isinstance(ap, dict)
                else "fake"
            }
        return out
    if t == "array":
        item = schema.get("items", {"type": "string"})
        n = max(1, int(schema.get("minItems", 1)))
        return [fill_schema(item, defs=defs, key=key, depth=depth + 1) for _ in range(n)]
    if t == "integer":
        lo = schema.get("minimum", schema.get("exclusiveMinimum", 0))
        return int(lo) + 1 if "exclusiveMinimum" in schema else int(lo if lo is not None else 1)
    if t == "number":
        if "exclusiveMinimum" in schema and "exclusiveMaximum" in schema:
            return (schema["exclusiveMinimum"] + schema["exclusiveMaximum"]) / 2
        return 0.5
    if t == "boolean":
        return True
    if t == "null":
        return None
    # string
    if "markdown" in key:
        return f"## {key}\n\nFake protocol text for `{key}` generated by the FakeLLM. Sensitivity, specificity and the locked algorithm version v2.1.0 are described here, together with the reference standard, washout, image quality exclusion and code access statements."
    if key.endswith("_id") or key == "id":
        return "fake-id"
    if key in ("status",):
        return "pass"
    return f"fake {key}"


@dataclass
class FakeLLM:
    name: str = "fake"
    overrides: dict[str, Callable[[str, list[LLMMessage], dict[str, Any] | None], Any] | Any] = (
        field(default_factory=dict)
    )
    calls: list[dict[str, Any]] = field(default_factory=list)

    async def complete(
        self,
        *,
        system: str,
        messages: list[LLMMessage],
        json_schema: dict[str, Any] | None = None,
        max_tokens: int | None = None,
        temperature: float | None = None,
    ) -> LLMResponse:
        self.calls.append({"system": system, "messages": messages, "json_schema": json_schema})
        haystack = system + "\n" + (messages[0].content if messages else "")
        for route, handler in self.overrides.items():
            if re.search(route, haystack):
                value = handler(system, messages, json_schema) if callable(handler) else handler
                break
        else:
            value = (
                fill_schema(json_schema)
                if json_schema
                else f"FAKE RESPONSE for: {messages[-1].content[:60] if messages else ''}"
            )
        if json_schema:
            import json

            return LLMResponse(
                text=json.dumps(value, ensure_ascii=False),
                parsed=value,
                model="fake",
                input_tokens=10,
                output_tokens=10,
                stop_reason="stop",
            )
        return LLMResponse(
            text=str(value),
            parsed=None,
            model="fake",
            input_tokens=10,
            output_tokens=10,
            stop_reason="stop",
        )
